const getTwoDigitWord = (n: number): string => {
  if (n <= 0) return '';
  return nepaliWordsMap[n] || String(n);
};

export const numberToNepaliWords = (amount: number): string => {
  const rounded = Math.round(Math.abs(amount));
  if (rounded === 0) return 'शून्य रुपैयाँ मात्र';

  let n = rounded;
  const parts: string[] = [];

  // करोड (Crore) - 10,000,000
  const crore = Math.floor(n / 10000000);
  if (crore > 0) {
    parts.push(`${getTwoDigitWord(crore)} करोड`);
    n %= 10000000;
  }

  // लाख (Lakh) - 100,000
  const lakh = Math.floor(n / 100000);
  if (lakh > 0) {
    parts.push(`${getTwoDigitWord(lakh)} लाख`);
    n %= 100000;
  }

  // हजार (Thousand) - 1,000
  const thousand = Math.floor(n / 1000);
  if (thousand > 0) {
    parts.push(`${getTwoDigitWord(thousand)} हजार`);
    n %= 1000;
  }

  // सय (Hundred) - 100
  const hundred = Math.floor(n / 100);
  if (hundred > 0) {
    parts.push(`${nepaliWordsMap[hundred] || hundred} सय`);
    n %= 100;
  }

  // Remaining 1-99
  if (n > 0) {
    parts.push(getTwoDigitWord(n));
  }

  return `${parts.join(' ')} रुपैयाँ मात्र`;
};
