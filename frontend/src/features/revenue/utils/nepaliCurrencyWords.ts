const nepaliDigits = ['०', '१', '२', '३', '४', '५', '६', '७', '८', '९'];

export const toNepaliDigits = (num: number | string): string => {
  return String(num).replace(/\d/g, (d) => nepaliDigits[parseInt(d, 10)]);
};

