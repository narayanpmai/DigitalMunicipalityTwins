    cleaned = re.sub(r'[^\w\s\u0900-\u097F]', ' ', query.lower())
    words = set(cleaned.split())

    best_match = None
    best_score = 0

    for item in BENIGHAT_KNOWLEDGE:
        score = 0
        for kw in item["keywords"]:
            kw_clean = kw.lower()
            if kw_clean in query.lower():
                score += 3
            for w in words:
                if len(w) > 2 and (w in kw_clean or kw_clean in w):
                    score += 1

        if score > best_score:
            best_score = score
            best_match = item

