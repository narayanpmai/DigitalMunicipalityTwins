                    citizenship_no=b_data.get("citizenshipNo", ""),
                    pan_number=b_data.get("panNumber", ""),
                    ward_number=b_data["wardNumber"],
                    tole_address=b_data["toleAddress"],
                    initial_capital=cap,
                    license_fee=fee,
