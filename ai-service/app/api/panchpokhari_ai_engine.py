def clean_nepali_text(text: str) -> str:
    """Normalizes whitespace and common Nepali alternate spellings."""
    if not text:
        return ""
    t = text.strip().lower()
    # Normalize common variations
    t = t.replace("पाचपोखरी", "पाँचपोखरी")
    t = t.replace("थानपाल", "थाङपाल")
    t = t.replace("नक्सा पास", "नक्सापास")
    t = t.replace("जन्म दर्ता", "जन्मदर्ता")
    t = t.replace("मृत्यु दर्ता", "मृत्युदर्ता")
    t = t.replace("विवाह दर्ता", "विवाहदर्ता")
    t = t.replace("बसाइ सराई", "बसाइँसराइ")
    t = t.replace("बसाइँ सराई", "बसाइँसराइ")
    t = t.replace("नाता प्रमाणीकरण", "नाता प्रमाणित")
    return t

def extract_ward_number(text: str) -> Optional[int]:
    """Extracts ward number (1-8) in either Devanagari or Arabic numerals."""
    nepali_digits = {'०': 0, '१': 1, '२': 2, '३': 3, '४': 4, '५': 5, '६': 6, '७': 7, '८': 8, '९': 9}
    
    # Try finding patterns like वडा ३, वडा नं. २, वडा नम्बर ५, ward 4
    match = re.search(r'(?:वडा|ward)\s*(?:नं|नम्बर|no\.?)?\s*([०-९\d]+)', text, re.IGNORECASE)
    if match:
        digit_str = match.group(1)
        val = 0
        for char in digit_str:
            if char in nepali_digits:
                val = val * 10 + nepali_digits[char]
            elif char.isdigit():
                val = val * 10 + int(char)
        if 1 <= val <= 8:
            return val
            
    # Also check if text just mentions isolated ward numbers with context
    for nep_d, arabic_d in nepali_digits.items():
        if nep_d in text and f"वडा {nep_d}" in text:
            return arabic_d
            
    return None

